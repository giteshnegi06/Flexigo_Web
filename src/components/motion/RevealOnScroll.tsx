"use client";
// Fades and lifts every element marked data-reveal as it scrolls into view.
// Content stays visible if JavaScript is off or the visitor prefers reduced motion.
import { usePathname } from "next/navigation";
import { gsap } from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { useGSAP } from "@gsap/react";

gsap.registerPlugin(ScrollTrigger, useGSAP);

export function RevealOnScroll() {
  const pathname = usePathname();
  useGSAP(
    () => {
      const mm = gsap.matchMedia();
      mm.add("(prefers-reduced-motion: no-preference)", () => {
        const items = gsap.utils.toArray<HTMLElement>("[data-reveal]");
        if (!items.length) return;
        gsap.set(items, { autoAlpha: 0, y: 28 });
        ScrollTrigger.batch(items, {
          start: "top 88%",
          once: true,
          onEnter: (batch) => gsap.to(batch, { autoAlpha: 1, y: 0, duration: 0.8, ease: "power3.out", stagger: 0.08, overwrite: true }),
        });
        ScrollTrigger.refresh();
      });
      return () => mm.revert();
    },
    { dependencies: [pathname], revertOnUpdate: true },
  );
  return null;
}
